"""`gj eval build-cases`: render the evaluation v0.2.0 authoring source to YAML.

Writes evaluation/cases/v0.2.0/<module>.yaml, evaluation/seeds/v0.2.0.yaml, the side=eval scenarios of
data/scenarios/behavioural_scenarios.yaml (the training side of the registry is kept) and the `cases`
block of evaluation/leakage/v0.2.0.yaml (its hand-maintained overlap lists are kept).
`check=True` renders in memory and reports files that differ from the committed ones.
"""
import importlib
import sys

import yaml

from gjcore.io import load_yaml
from gjcore.paths import REPO_ROOT, rel

VERSION = "0.2.0"
_PKG = "evaluation.builders.v0_2_0"
_REGISTRY = REPO_ROOT / "data" / "scenarios" / "behavioural_scenarios.yaml"
_LEAKAGE = REPO_ROOT / "evaluation" / "leakage" / f"v{VERSION}.yaml"
_LEAKAGE_HEAD = f"""# Evaluation leakage metadata — eval v{VERSION} (read by `gj leakage` and the release gates).
#
# `cases` is GENERATED by `gj eval build-cases` from the builder (scenario group, seed and behavioural template of
# every case). Everything below it — notes, template_overlaps, seed_overlaps — is maintained by hand and preserved
# when the file is regenerated: reviewers record dispositions here (set `disposition` and `decided_by`).
#
# template_overlaps lists evaluation cases or steps whose decision structure resembles a training example,
# found by reading every case against all training scenarios plus the automated candidates of `gj leakage`.
# strength: strong = same decisive condition and same decision as a training scenario; medium = same decision
# under a different decisive condition; topic_only = same subject, different decision; none = automated
# candidate, reviewed as coincidental. `proposed_disposition` is the case author's suggestion; `disposition`
# stays `open` until a human reviewer decides.
"""


def _dump(obj):
    return yaml.safe_dump(obj, allow_unicode=True, sort_keys=False, width=120)


def _leakage_metadata(cases):
    """The eval-side leakage sidecar: generated `cases` block + hand-maintained overlap lists (preserved)."""
    old = load_yaml(_LEAKAGE) if _LEAKAGE.exists() else {}
    old = old or {}
    meta = {"eval_version": VERSION,
            "cases": {c["id"]: {"scenario_group": c["scenario_group"],
                                "behavior_template": "bt-" + c["scenario_group"].removeprefix("bs-ev-"),
                                "seed_origin": c["seed_id"], "author": "claude-code-agent"} for c in cases}}
    if old.get("notes"):
        meta["notes"] = old["notes"]
    meta["template_overlaps"] = old.get("template_overlaps") or []
    if old.get("seed_overlaps"):
        meta["seed_overlaps"] = old["seed_overlaps"]
    return _LEAKAGE_HEAD + _dump(meta)


def render():
    """{path: text} for every generated file."""
    common = importlib.import_module(f"{_PKG}.common")
    common.SEEDS.clear(), common.SCENARIOS.clear(), common.CASES.clear()
    pkg = importlib.import_module(_PKG)
    files = {}
    for name in pkg.MODULES:
        start = len(common.CASES)
        full = f"{_PKG}.{name}"
        if full in sys.modules:
            importlib.reload(sys.modules[full])  # re-registers its cases
        else:
            importlib.import_module(full)
        cases = common.CASES[start:]
        head = (f"# Evaluation v{VERSION} — {name}. GENERATED from evaluation/builders/v0_2_0/{name}.py by "
                "`gj eval build-cases`; edit the builder, not this file.\n")
        files[REPO_ROOT / "evaluation" / "cases" / f"v{VERSION}" / f"{name}.yaml"] = head + _dump({"cases": cases})
    seeds_head = (f"# Evaluation seeds v{VERSION}: independent situations written before the cases (docs/EVALUATION_V0.2_DESIGN.md).\n"
                  "# GENERATED by `gj eval build-cases`.\n")
    files[REPO_ROOT / "evaluation" / "seeds" / f"v{VERSION}.yaml"] = seeds_head + _dump(
        {"eval_version": VERSION, "seeds": common.SEEDS})
    files[_LEAKAGE] = _leakage_metadata(common.CASES)
    text = _REGISTRY.read_text(encoding="utf-8")
    header = "".join(l for l in text.splitlines(keepends=True) if l.startswith("#"))
    reg = load_yaml(_REGISTRY)
    reg["scenarios"] = [s for s in reg["scenarios"] if s["side"] != "eval"] + common.SCENARIOS
    files[_REGISTRY] = header + _dump(reg)
    return files


def run(check=False):
    files = render()
    stale = []
    for path, text in files.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check:
        for p in stale:
            print(f"✗ {rel(p)} differs from the builder output — run `gj eval build-cases`")
        if not stale:
            print(f"✓ {len(files)} generated file(s) match the builder output.")
        return 1 if stale else 0
    print(f"Wrote {len(stale)} file(s): " + ", ".join(rel(p) for p in stale) if stale else "Nothing changed.")
    return 0
