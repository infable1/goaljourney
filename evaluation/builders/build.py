"""`gj eval build-cases`: render the evaluation v0.2.0 authoring source to YAML.

Writes evaluation/cases/v0.2.0/<module>.yaml, evaluation/seeds/v0.2.0.yaml, and the side=eval
scenarios of data/scenarios/behavioural_scenarios.yaml (the training side of the registry is kept).
`check=True` renders in memory and reports files that differ from the committed ones.
"""
import importlib
import sys

import yaml

from gjcore.io import load_yaml
from gjcore.paths import REPO_ROOT, rel

VERSION = "0.2.0"
_PKG = "evaluation.builders.v0_2_0"
_REGISTRY = REPO_ROOT / "data" / "scenarios" / "behavioural_scenarios.yaml"


def _dump(obj):
    return yaml.safe_dump(obj, allow_unicode=True, sort_keys=False, width=120)


def render():
    """{path: text} for every generated file."""
    common = importlib.import_module(f"{_PKG}.common")
    common.SEEDS.clear(), common.SCENARIOS.clear(), common.CASES.clear()
    pkg = importlib.import_module(_PKG)
    files = {}
    for name in pkg.MODULES:
        start = len(common.CASES)
        full = f"{_PKG}.{name}"
        if full in sys.modules:
            importlib.reload(sys.modules[full])  # re-registers its cases
        else:
            importlib.import_module(full)
        cases = common.CASES[start:]
        head = (f"# Evaluation v{VERSION} — {name}. GENERATED from evaluation/builders/v0_2_0/{name}.py by "
                "`gj eval build-cases`; edit the builder, not this file.\n")
        files[REPO_ROOT / "evaluation" / "cases" / f"v{VERSION}" / f"{name}.yaml"] = head + _dump({"cases": cases})
    seeds_head = (f"# Evaluation seeds v{VERSION}: independent situations written before the cases (docs/EVALUATION_V0.2_DESIGN.md).\n"
                  "# GENERATED by `gj eval build-cases`.\n")
    files[REPO_ROOT / "evaluation" / "seeds" / f"v{VERSION}.yaml"] = seeds_head + _dump(
        {"eval_version": VERSION, "seeds": common.SEEDS})
    text = _REGISTRY.read_text(encoding="utf-8")
    header = "".join(l for l in text.splitlines(keepends=True) if l.startswith("#"))
    reg = load_yaml(_REGISTRY)
    reg["scenarios"] = [s for s in reg["scenarios"] if s["side"] != "eval"] + common.SCENARIOS
    files[_REGISTRY] = header + _dump(reg)
    return files


def run(check=False):
    files = render()
    stale = []
    for path, text in files.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check:
        for p in stale:
            print(f"✗ {rel(p)} differs from the builder output — run `gj eval build-cases`")
        return 1 if stale else 0
    print(f"Wrote {len(stale)} file(s): " + ", ".join(rel(p) for p in stale) if stale else "Nothing changed.")
    return 0
